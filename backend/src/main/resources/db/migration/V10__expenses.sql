-- I3: expenses. A new table only, so nothing existing is rewritten and no backfill
-- is needed. Category and paid_from are stored as enum names with CHECKs, like
-- sales.payment_method: the lists are fixed, not a per-shop setting.
create table expenses (
    id           bigint generated by default as identity primary key,
    shop_id      bigint        not null references shops (id),
    expense_date date          not null,
    amount       numeric(12, 2) not null check (amount > 0),
    category     varchar(20)   not null
        check (category in ('RENT', 'SALARIES', 'TRANSPORT', 'ELECTRICITY_WATER', 'PACKAGING', 'SUPPLIES', 'OTHER')),
    paid_from    varchar(10)   not null check (paid_from in ('CASH', 'MOMO', 'OTHER')),
    note         text,
    created_by   bigint        not null references users (id),
    created_at   timestamp with time zone not null,
    voided       boolean       not null default false,
    voided_at    timestamp with time zone,
    voided_by    bigint references users (id),
    void_note    text
);

-- Every read is "this shop, this date range", and the totals add paid_from.
create index expenses_shop_date_idx on expenses (shop_id, expense_date);
