-- I5: price and cost history. A new table only, so no existing row is rewritten.
-- One row per change to a product's price or cost; the app writes it (see
-- ProductPriceHistoryService). The seed gives every existing product a starting
-- point so the first real change can show a "before" value.
create table product_price_history (
    id          bigint generated by default as identity primary key,
    shop_id     bigint         not null references shops (id),
    product_id  bigint         not null,
    price       numeric(10, 2) not null,
    cost_price  numeric(12, 2),
    changed_at  timestamp with time zone not null,
    -- Null on the seed rows: "the history starts here", nobody changed anything.
    changed_by  bigint references users (id),
    -- Same guard as stock_movements: the history row's shop must be its product's shop.
    foreign key (product_id, shop_id) references products (id, shop_id)
);

create index product_price_history_product_idx on product_price_history (product_id, changed_at);

insert into product_price_history (shop_id, product_id, price, cost_price, changed_at, changed_by)
select shop_id, id, price, cost_price, now(), null from products;
